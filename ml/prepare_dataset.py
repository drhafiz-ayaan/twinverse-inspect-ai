#!/usr/bin/env python3
"""Split a flat YOLO-format dataset into train/val/test and write data.yaml.

Expects a source directory containing images and matching .txt label files,
either side by side or in separate images/ and labels/ subdirectories:

    source/
      images/  crack_001.jpg  crack_002.jpg  ...
      labels/  crack_001.txt  crack_002.txt  ...

Usage:
    python ml/prepare_dataset.py \\
        --source ~/downloads/concrete-cracks \\
        --output ml/datasets/concrete \\
        --classes crack corrosion surface_damage

Class names should match the aliases in backend/app/services/inference.py so
detections map onto the four defect classes rather than being discarded.
"""

from __future__ import annotations

import argparse
import random
import shutil
import sys
from collections import Counter
from pathlib import Path

IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff", ".webp"}


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("--source", required=True, help="Directory holding images and labels")
    p.add_argument("--output", required=True, help="Destination dataset root")
    p.add_argument("--classes", nargs="+", required=True,
                   help="Class names in label-index order")
    p.add_argument("--train", type=float, default=0.7)
    p.add_argument("--val", type=float, default=0.2)
    p.add_argument("--seed", type=int, default=42,
                   help="Fixed so splits are reproducible across runs")
    p.add_argument("--copy", action="store_true",
                   help="Copy files instead of symlinking (uses more disk)")
    return p.parse_args()


def find_pairs(source: Path) -> list[tuple[Path, Path | None]]:
    """Locate (image, label) pairs, tolerating both common layouts."""
    img_dir = source / "images" if (source / "images").is_dir() else source
    lbl_dir = source / "labels" if (source / "labels").is_dir() else source

    pairs: list[tuple[Path, Path | None]] = []
    for img in sorted(img_dir.rglob("*")):
        if img.suffix.lower() not in IMAGE_SUFFIXES or not img.is_file():
            continue
        label = lbl_dir / f"{img.stem}.txt"
        pairs.append((img, label if label.is_file() else None))
    return pairs


def place(src: Path, dst: Path, copy: bool) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists() or dst.is_symlink():
        dst.unlink()
    if copy:
        shutil.copy2(src, dst)
    else:
        # Symlink by default: image datasets run to gigabytes and there is no
        # reason to hold two copies on one machine.
        dst.symlink_to(src.resolve())


def main() -> int:
    args = parse_args()

    if not 0 < args.train < 1 or not 0 <= args.val < 1 or args.train + args.val >= 1:
        sys.exit("--train and --val must be fractions summing to less than 1")

    source = Path(args.source).expanduser().resolve()
    if not source.is_dir():
        sys.exit(f"source directory not found: {source}")

    output = Path(args.output).expanduser().resolve()

    pairs = find_pairs(source)
    if not pairs:
        sys.exit(f"no images found under {source}")

    unlabelled = [p for p, lbl in pairs if lbl is None]
    if unlabelled:
        print(f"! {len(unlabelled)} image(s) have no label file and will be treated "
              f"as backgrounds (e.g. {unlabelled[0].name})", file=sys.stderr)

    random.Random(args.seed).shuffle(pairs)
    n = len(pairs)
    n_train = int(n * args.train)
    n_val = int(n * args.val)
    splits = {
        "train": pairs[:n_train],
        "val": pairs[n_train:n_train + n_val],
        "test": pairs[n_train + n_val:],
    }

    counts: Counter[str] = Counter()
    for split, items in splits.items():
        for img, label in items:
            place(img, output / "images" / split / img.name, args.copy)
            if label is not None:
                place(label, output / "labels" / split / label.name, args.copy)
                for line in label.read_text().splitlines():
                    if line.strip():
                        idx = int(line.split()[0])
                        if 0 <= idx < len(args.classes):
                            counts[args.classes[idx]] += 1

    yaml_path = output / "data.yaml"
    names = "\n".join(f"  {i}: {c}" for i, c in enumerate(args.classes))
    yaml_path.write_text(
        f"# Generated by ml/prepare_dataset.py — do not edit by hand.\n"
        f"path: {output}\n"
        f"train: images/train\n"
        f"val: images/val\n"
        f"test: images/test\n"
        f"nc: {len(args.classes)}\n"
        f"names:\n{names}\n"
    )

    print(f"\ndataset written to {output}")
    for split, items in splits.items():
        print(f"  {split:5} {len(items):6} images")
    print("\ninstances per class:")
    for cls in args.classes:
        marker = "" if counts[cls] else "   <- no instances, check label indices"
        print(f"  {cls:20} {counts[cls]:6}{marker}")
    print(f"\ndata.yaml: {yaml_path}")
    print(f"train with:\n  python ml/train.py --data {yaml_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
